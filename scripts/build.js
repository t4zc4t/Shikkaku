// blend two hex colours, t = share of b
function mix(a, b, t) {
  const pa = a.slice(1, 7).match(/../g).map(h => parseInt(h, 16))
  const pb = b.slice(1, 7).match(/../g).map(h => parseInt(h, 16))
  return '#' + pa.map((v, i) => Math.round(v + (pb[i] - v) * t).toString(16).padStart(2, '0')).join('')
}
const lift = (c, t = 0.22) => mix(c, '#ffffff', t)
const sink = (c, t = 0.2) => mix(c, '#000000', t)


