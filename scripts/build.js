function semantic(p) {
  return {
    parameter: { foreground: p.param, italic: true },
    property: p.property,
    'property.readonly': p.property,
    enumMember: p.constant,
    'variable.readonly': p.variable,
    'variable.defaultLibrary': p.type,
    'function.defaultLibrary': p.func,
    namespace: p.type,
    typeParameter: p.type,
    decorator: { foreground: p.func, italic: true },
  }
}

function build(p) {
  return {
    $schema: 'vscode://schemas/color-theme',
    name: p.name,
    type: p.type,
    semanticHighlighting: true,
    colors: colors(p),
    tokenColors: tokens(p),
    semanticTokenColors: semantic(p),
  }
}

